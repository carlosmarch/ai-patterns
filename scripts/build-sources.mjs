#!/usr/bin/env node
// Writes src/registry/sources.generated.ts: every pattern's component.tsx
// source as a string, keyed by "<category>/<slug>".
//
// The site shows these sources (Code tab, MCP server, JSON API, Markdown
// twins). Reading them with `fs` at request time breaks on Cloudflare
// Workers, which have no project filesystem, so they're bundled as a
// module instead. Runs automatically before `npm run dev` / `npm run build`.
//
// Usage: node scripts/build-sources.mjs

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const registryDir = join(repoRoot, "src/registry");
const outFile = join(registryDir, "sources.generated.ts");

const dirs = (p) =>
  readdirSync(p, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

const lines = [];
for (const category of dirs(registryDir)) {
  for (const slug of dirs(join(registryDir, category))) {
    const file = join(registryDir, category, slug, "component.tsx");
    if (!existsSync(file)) continue;
    lines.push(`  ${JSON.stringify(`${category}/${slug}`)}: ${JSON.stringify(readFileSync(file, "utf8"))},`);
  }
}

const out = `// Generated by scripts/build-sources.mjs — do not edit by hand.
// Each pattern's component.tsx source, bundled so no route needs \`fs\` at runtime.

export const componentSources: Record<string, string> = {
${lines.join("\n")}
};
`;

if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== out) {
  writeFileSync(outFile, out);
  console.log(`Wrote ${lines.length} component sources to src/registry/sources.generated.ts`);
}
